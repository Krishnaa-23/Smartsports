import sqlite3
import pandas as pd
from pathlib import Path


BASE_DIR = Path(__file__).resolve().parent.parent
DATABASE_PATH = BASE_DIR / "database" / "sports_booking.db"


def get_revenue_by_court():
    """
    Calculate historical revenue generated by each court.
    """

    connection = sqlite3.connect(DATABASE_PATH)

    query = """
        SELECT
            c.court_name,
            c.sport,
            COUNT(b.booking_id) AS total_bookings,
            COALESCE(SUM(b.amount_paid), 0) AS revenue
        FROM courts c
        LEFT JOIN slots s
            ON c.court_id = s.court_id
        LEFT JOIN bookings b
            ON s.slot_id = b.slot_id
            AND b.status = 'Confirmed'
        WHERE s.slot_date < '2026-09-15'
        GROUP BY c.court_id
        ORDER BY revenue DESC
    """

    result = pd.read_sql_query(query, connection)

    connection.close()

    result["revenue"] = result["revenue"].round(2)

    return result


def get_revenue_by_time():
    """
    Calculate historical revenue generated by each time slot.
    """

    connection = sqlite3.connect(DATABASE_PATH)

    query = """
        SELECT
            s.start_time,
            COUNT(b.booking_id) AS total_bookings,
            COALESCE(SUM(b.amount_paid), 0) AS revenue
        FROM slots s
        LEFT JOIN bookings b
            ON s.slot_id = b.slot_id
            AND b.status = 'Confirmed'
        WHERE s.slot_date < '2026-09-15'
        GROUP BY s.start_time
        ORDER BY s.start_time
    """

    result = pd.read_sql_query(query, connection)

    connection.close()

    result["revenue"] = result["revenue"].round(2)

    return result
def calculate_slot_economics(base_price, discount_percentage=0):
    """
    Estimate the revenue and profit impact of a discount.

    The operating cost rate is an estimated business assumption
    for the portfolio project and can be changed later.
    """

    operating_cost_rate = 0.40

    discount_amount = (
        base_price * discount_percentage / 100
    )

    discounted_price = base_price - discount_amount

    estimated_operating_cost = (
        base_price * operating_cost_rate
    )

    full_price_profit = (
        base_price - estimated_operating_cost
    )

    discounted_profit = (
        discounted_price - estimated_operating_cost
    )

    profit_reduction = (
        full_price_profit - discounted_profit
    )

    if full_price_profit > 0:
        profit_margin = (
            discounted_profit / discounted_price
        ) * 100
    else:
        profit_margin = 0

    return {
        "base_price": round(base_price, 2),
        "discount_percentage": discount_percentage,
        "discount_amount": round(discount_amount, 2),
        "discounted_price": round(discounted_price, 2),
        "estimated_operating_cost": round(
            estimated_operating_cost, 2
        ),
        "full_price_profit": round(
            full_price_profit, 2
        ),
        "discounted_profit": round(
            discounted_profit, 2
        ),
        "profit_reduction": round(
            profit_reduction, 2
        ),
        "profit_margin": round(
            profit_margin, 2
        )
    }